type IconProps = Omit<SVGProps<SVGSVGElement>, "viewBox"> & { size?: number };

type IconSpec = {
  box: number;
  stroke?: number;
  paths: readonly string[];
  filled?: boolean;
};

function createIcon(displayName: string, spec: IconSpec) {
  function Icon({ size = spec.box, ...rest }: IconProps) {
    return (
      <svg
        width={size}
        height={size}
        viewBox={`0 0 ${spec.box} ${spec.box}`}
        fill={spec.filled ? "currentColor" : "none"}
        stroke={spec.filled ? undefined : "currentColor"}
        strokeWidth={spec.stroke}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        focusable="false"
        {...rest}
      >
        {spec.paths.map((d) => (
          <path key={d} d={d} />
        ))}
      </svg>
    );
  }
  Icon.displayName = displayName;
  return Icon;
}

